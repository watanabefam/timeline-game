#!/usr/bin/env node
/*
 * scripts/gen-deck-manifest.mjs
 * ------------------------------------------------------------------
 * Generates decks/manifest.json AND decks/manifest.js from the files actually
 * present in decks/, so the deck list is never hand-maintained (the old
 * hand-written list plus a hardcoded duplicate in timeline.js drifted and
 * silently dropped a deck).
 *
 * Two artefacts, one source of truth:
 *   manifest.json — read by the Node tooling (validate, geo, pipeline).
 *   manifest.js   — a classic script the browser injects. fetch()-ing the .json
 *                   is blocked by CORS when index.html is opened from disk
 *                   (file://, origin "null"), which dropped every deck; a
 *                   <script> has no such restriction, so the runtime reads this
 *                   global and only falls back to fetch when it is absent.
 *
 * Each entry's `revision` is a content hash, so returning players always
 * fetch a changed deck and never a stale one.
 *
 * Run:
 *   node scripts/gen-deck-manifest.mjs          # write both manifests
 *   node scripts/gen-deck-manifest.mjs --check  # exit 1 if either is stale (CI)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const decksDir = join(here, "..", "decks");
const manifestPath = join(decksDir, "manifest.json");

// Decks that predate full source provenance. Their SOURCE_MISSING findings are
// downgraded to warnings by the pipeline gate while sources are backfilled.
// New decks are deliberately NOT listed here and face the full gate.
const GRANDFATHERED = new Set(["classical-conversations.js", "world-literature.js"]);

const decks = readdirSync(decksDir)
  .filter((f) => f.endsWith(".js") && f !== "manifest.js")
  .sort()
  .map((file) => {
    const bytes = readFileSync(join(decksDir, file));
    const entry = {
      file,
      revision: createHash("sha256").update(bytes).digest("hex").slice(0, 12),
      bytes: bytes.length,
    };
    if (GRANDFATHERED.has(file)) entry.grandfathered = true;
    return entry;
  });

const manifest = { schemaVersion: 2, decks };
const nextJson = JSON.stringify(manifest, null, 2) + "\n";
const nextJs =
  "/* GENERATED by scripts/gen-deck-manifest.mjs — do not edit by hand. */\n" +
  "window.DECK_MANIFEST = " + JSON.stringify(manifest, null, 2) + ";\n";
const jsPath = join(decksDir, "manifest.js");
const check = process.argv.includes("--check");

if (check) {
  const curJson = existsSync(manifestPath) ? readFileSync(manifestPath, "utf8") : "";
  const curJs = existsSync(jsPath) ? readFileSync(jsPath, "utf8") : "";
  if (curJson !== nextJson || curJs !== nextJs) {
    console.error(
      "✗ decks/manifest.json / manifest.js are out of date — run: node scripts/gen-deck-manifest.mjs"
    );
    process.exit(1);
  }
  console.log(`✓ decks/manifest.* up to date (${decks.length} decks).`);
  process.exit(0);
}

writeFileSync(manifestPath, nextJson);
writeFileSync(jsPath, nextJs);
console.log(`✓ Wrote decks/manifest.json + manifest.js (${decks.length} decks).`);
